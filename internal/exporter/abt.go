// CheckTypeFromInOut converts ZKTeco numeric InOutMode to ZKTime 5.0 CheckType character.
func CheckTypeFromInOut(inOutMode int) string {
	switch inOutMode {
	case 0:
		return "I"
	case 1:
		return "O"
	case 2:
		return "0"
	case 3:
		return "1"
	case 4:
		return "i"
	case 5:
		return "o"
	default:
		return "I"
	}
}

// InOutFromCheckType converts ZKTime 5.0 CheckType character back to ZKTeco InOutMode.
func InOutFromCheckType(ct string) int {
	switch strings.TrimSpace(ct) {
	case "I":
		return 0
	case "O":
		return 1
	case "0":
		return 2
	case "1":
		return 3
	case "i":
		return 4
	case "o":
		return 5
	default:
		if n, err := strconv.Atoi(strings.TrimSpace(ct)); err == nil {
			return n
		}
		return 0
	}
}

func verifyLabelForABT(code int) string {
	switch code {
	case 0:
		return "密码"
	case 1:
		return "指纹"
	case 2, 3, 4:
		return "刷卡"
	case 15:
		return "人脸"
	case 25:
		return "掌纹"
	default:
		return fmt.Sprintf("方式(%d)", code)
	}
}

func inOutLabelForABT(code int) string {
	switch code {
	case 0:
		return "上班签到"
	case 1:
		return "下班签退"
	case 2:
		return "外出"
	case 3:
		return "外出返回"
	case 4:
		return "加班签到"
	case 5:
		return "加班签退"
	case 255:
		return "打卡"
	default:
		return fmt.Sprintf("状态(%d)", code)
	}
}

func sanitizeTabField(s string) string {
	s = strings.ReplaceAll(s, "\t", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.TrimSpace(s)
}

// FormatZKTimePlaintext serializes attendance records into the exact 8-column Tab-separated,
// GBK-encoded, CRLF-terminated text format generated by legacy ZKTime 5.0 Att.exe:
// BadgeNumber \t yyyy-MM-dd HH:mm:ss \t SensorID \t VerifyCode \t Name \t CheckType \t WorkCode \t UserExtFmt \r\n
func FormatZKTimePlaintext(records []models.AttendanceRecord) ([]byte, error) {
	sorted := append([]models.AttendanceRecord(nil), records...)
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].Timestamp != sorted[j].Timestamp {
			return sorted[i].Timestamp < sorted[j].Timestamp
		}
		if sorted[i].SensorID != sorted[j].SensorID {
			return sorted[i].SensorID < sorted[j].SensorID
		}
		return sorted[i].PIN < sorted[j].PIN
	})

	var sb strings.Builder
	sb.Grow(len(sorted) * 44)
	for _, r := range sorted {
		pin := sanitizeTabField(r.PIN)
		ts := sanitizeTabField(r.Timestamp)
		sensor := sanitizeTabField(r.SensorID)
		if sensor == "" {
			sensor = "1"
		}
		name := sanitizeTabField(r.Name)
		checkType := CheckTypeFromInOut(r.InOutMode)
		sb.WriteString(pin)
		sb.WriteByte('\t')
		sb.WriteString(ts)
		sb.WriteByte('\t')
		sb.WriteString(sensor)
		sb.WriteByte('\t')
		sb.WriteString(strconv.Itoa(r.VerifyMode))
		sb.WriteByte('\t')
		sb.WriteString(name)
		sb.WriteByte('\t')
		sb.WriteString(checkType)
		sb.WriteByte('\t')
		sb.WriteString(strconv.Itoa(r.WorkCode))
		sb.WriteString("\t0\r\n")
	}

	enc := encoding.ReplaceUnsupported(simplifiedchinese.GBK.NewEncoder())
	return enc.Bytes([]byte(sb.String()))
}

// ExportABT writes a legacy ZKTime 5.0 compatible .ABT file (4-byte LE origSize + LH5 compressed GBK text).
func ExportABT(path string, records []models.AttendanceRecord) error {
	plain, err := FormatZKTimePlaintext(records)
	if err != nil {
		return fmt.Errorf("编码 ABT 明文失败: %w", err)
	}
	compressed := EncodeLH5(plain)
	return os.WriteFile(path, compressed, 0o644)
}

// ParseZKTimePlaintext parses GBK Tab-separated (or legacy comma-separated) ZKTime 5.0 text bytes.
func ParseZKTimePlaintext(rawGBK []byte, devBySensor map[string]models.DeviceConfig) ([]models.AttendanceRecord, error) {
	decoded, err := simplifiedchinese.GB18030.NewDecoder().Bytes(rawGBK)
	if err != nil {
		// Fallback to raw bytes as UTF-8
		decoded = rawGBK
	}
	text := strings.TrimPrefix(string(decoded), "\uFEFF")
	lines := strings.Split(text, "\n")

	out := make([]models.AttendanceRecord, 0, len(lines))
	for _, rawLine := range lines {
		line := strings.TrimRight(rawLine, "\r")
		if strings.TrimSpace(line) == "" {
			continue
		}
		var cols []string
		if strings.Contains(line, "\t") {
			cols = strings.Split(line, "\t")
		} else if strings.Contains(line, ",") {
			cols = strings.Split(line, ",")
		} else {
			continue
		}
		if len(cols) < 2 {
			continue
		}
		pin := strings.TrimSpace(cols[0])
		ts := strings.TrimSpace(cols[1])
		// Skip optional header row if present
		if strings.EqualFold(pin, "BadgeNumber") || pin == "工号" || len(ts) < 10 {
			continue
		}

		sensorID := ""
		if len(cols) > 2 {
			sensorID = strings.TrimSpace(cols[2])
		}
		verifyMode := 0
		if len(cols) > 3 {
			verifyMode, _ = strconv.Atoi(strings.TrimSpace(cols[3]))
		}
		name := ""
		if len(cols) > 4 {
			name = strings.TrimSpace(cols[4])
		}
		inOutMode := 0
		if len(cols) > 5 {
			inOutMode = InOutFromCheckType(cols[5])
		}
		workCode := 0
		if len(cols) > 6 {
			workCode, _ = strconv.Atoi(strings.TrimSpace(cols[6]))
		}

		devID := "sensor_" + sensorID
		devName := fmt.Sprintf("外部考勤机 (%s)", sensorID)
		if sensorID == "" {
			devID = "abt_import"
			devName = "ABT 导入"
		}
		if cfg, ok := devBySensor[sensorID]; ok {
			devID = cfg.ID
			devName = cfg.Name
		}

		out = append(out, models.AttendanceRecord{
			DeviceID:    devID,
			DeviceName:  devName,
			SensorID:    sensorID,
			PIN:         pin,
			Name:        name,
			Timestamp:   ts,
			VerifyMode:  verifyMode,
			VerifyLabel: verifyLabelForABT(verifyMode),
			InOutMode:   inOutMode,
			InOutLabel:  inOutLabelForABT(inOutMode),
			WorkCode:    workCode,
		})
	}
	return out, nil
}

// ParseABTFile reads a ZKTime 5.0 .ABT (LH5 compressed) or .TXT file and parses attendance records.
func ParseABTFile(path string, devBySensor map[string]models.DeviceConfig) ([]models.AttendanceRecord, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	ext := strings.ToLower(filepath.Ext(path))
	if ext == ".txt" {
		return ParseZKTimePlaintext(raw, devBySensor)
	}
	plain, err := DecodeLH5(raw)
	if err != nil {
		return nil, fmt.Errorf("解析 .ABT 压缩流失败: %w", err)
	}
	return ParseZKTimePlaintext(plain, devBySensor)
}
